/**
 * Step 3 — build the import payload and write the generated catalog DATA seed.
 *
 *   npx vite-node scripts/catalog-import/build.ts            # writes supabase/seeds/catalog_contracts.sql
 *   npx vite-node scripts/catalog-import/build.ts -- --check # fails if the committed seed is stale
 *
 * The seed contains ONE statement: `select private.catalog_import('<payload>'::jsonb)`.
 * It is idempotent (re-running changes nothing) and never touches orders, accounts or unrelated services.
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { buildImportPayload, type CategoryDef, type ExistingMapping } from '../../shared/catalog/build.ts'
import type { SourceContract } from '../../shared/catalog/source.ts'

const DATA = fileURLToPath(new URL('./data/', import.meta.url))
const OUTPUT = fileURLToPath(new URL('../../supabase/seeds/catalog_contracts.sql', import.meta.url))
const check = process.argv.includes('--check')
// --draft: import the services unpublished so they can be reviewed in the admin before customers see them
const draft = process.argv.includes('--draft')

const contracts: SourceContract[] = JSON.parse(readFileSync(`${DATA}source/contracts.source.json`, 'utf8'))
const categories: CategoryDef[] = JSON.parse(readFileSync(`${DATA}categories.json`, 'utf8'))
const mapping: ExistingMapping = JSON.parse(readFileSync(`${DATA}existing-catalog-mapping.json`, 'utf8'))
const specs = new Map<string, unknown>()
for (const f of readdirSync(`${DATA}specs/`).filter(x => x.endsWith('.json')).sort()) {
  specs.set(f.replace(/\.json$/, ''), JSON.parse(readFileSync(`${DATA}specs/${f}`, 'utf8')))
}

const { payload, problems } = buildImportPayload({ contracts, specs, categories, mapping, publish: !draft })
if (problems.length) {
  console.error(`✗ ${problems.length} problem(s):\n${problems.map(p => `  - ${p}`).join('\n')}`)
  process.exit(1)
}

const json = JSON.stringify(payload)
if (json.includes('$oqcat$')) throw new Error('payload contains the dollar-quote tag')
const sha = createHash('sha256').update(json).digest('hex')
const header = [
  '-- =====================================================================',
  '-- Catalog DATA: 64 contracts (32 individuals + 32 companies) and 17 sub-categories.',
  '--',
  '-- This is a SEED, not a migration: it depends on the top-level categories and the original services created by',
  '-- supabase/seed.sql (config.toml runs seed.sql first, then supabase/seeds/*.sql on db reset). On a database that already',
  '-- has them (local, hosted) apply it explicitly — it is idempotent and never touches orders, accounts or unrelated services:',
  '--   psql "<connection-url>" -f supabase/seeds/catalog_contracts.sql',
  '-- Hosted: apply ONLY after review/approval, then verify with  npm run catalog:verify -- --db <connection-url>',
  '-- GENERATED by scripts/catalog-import/build.ts — do not edit by hand; edit the data files and rebuild.',
  `-- batch ${payload.batchKey} · payload sha256 ${sha.slice(0, 16)}… · ${payload.services.length} services · ${payload.categories.length} sub-categories`,
  '--',
  '-- Idempotent: services are keyed by services.source_ref. Re-running reports every record as "matched".',
  '-- Needs the schema migrations 20261016174000 … 20261016174400 (hierarchy, pricing, campaign, import engine).',
  '-- Reused existing services (employment-contract, lease-agreement, company-governance) keep their id and',
  '-- history; changed forms become NEW published form versions. Orders/accounts are never touched.',
  '-- The launch campaign is NOT activated here (it stays disabled until an admin enables it).',
  ...(draft ? ['-- BUILT WITH --draft: services are imported UNPUBLISHED (status draft) — publish them from the admin when reviewed.'] : []),
  '-- =====================================================================',
  '',
].join('\n')
const sql = `${header}select private.catalog_import($oqcat$${json}$oqcat$::jsonb);\n`

if (check) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8') : ''
  if (current !== sql) {
    console.error('✗ supabase/seeds/catalog_contracts.sql is stale — run npm run catalog:build')
    process.exit(1)
  }
  console.log('✓ catalog seed is up to date')
}
else {
  writeFileSync(OUTPUT, sql, 'utf8')
  console.log(`wrote ${OUTPUT} (${(sql.length / 1024).toFixed(0)} KB) — ${payload.services.length} services, ${payload.categories.length} sub-categories`)
}
