// 4. form coverage
// ---------------------------------------------------------------------------
function formCoverage(): string {
  const lines: string[] = []
  const rows = contracts.map((c) => {
    const { report, compiled } = validateSpec(c, specs.get(c.ref))
    const items = sourceItems(c)
    return { c, report, compiled, items }
  })
  const sum = (f: (r: (typeof rows)[number]) => number) => rows.reduce((n, r) => n + f(r), 0)
  lines.push('# Dynamic form coverage — 64 contracts', '')
  lines.push('Each contract has its own form version generated from columns E–H of its workbook row (`scripts/catalog-import/data/specs/<REF>.json` → `shared/catalog/spec.ts` → published `service_form_versions`). The validator **fails the build** unless **every source item** (E1…, F1…, G1…, H1…) is covered by at least one field.', '')
  lines.push('## Totals', '', '| | |', '|---|---|',
    `| Source items (E party info / F technical-financial / G special conditions / H documents) | **${sum(r => allItemRefs(r.c).length)}** (E ${sum(r => r.items.E.length)} · F ${sum(r => r.items.F.length)} · G ${sum(r => r.items.G.length)} · H ${sum(r => r.items.H.length)}) |`,
    `| Items covered by a form field | **${sum(r => r.report.itemsCovered)}** (100%) |`,
    `| Form inputs generated | **${sum(r => r.report.inputCount)}** |`,
    `| — mandatory (\`required\`) | ${sum(r => r.report.required)} |`,
    `| — optional (explicit «إن وجد/اختياري» or a column-G customer choice) | ${sum(r => r.report.optional)} |`,
    `| — **mandatory status pending legal review** (optional at runtime, flagged \`legalReview\`) | ${sum(r => r.report.review)} |`,
    `| Document upload fields (required / optional) | ${sum(r => r.report.fileFields)} (${sum(r => r.report.requiredFiles)} / ${sum(r => r.report.fileFields - r.report.requiredFiles)}) |`,
    `| Structured list fields (repeaters) | ${sum(r => r.report.repeaters)} |`, '')
  lines.push('## Field types and steps', '',
    'Forms are grouped into numbered steps (sections): **1 Party details → 2 Contract details → 3 Financial and technical information → 4 Special and additional conditions → 5 Required documents**, followed by the platform’s review-and-submit step. A step with no items is omitted. Types used: text, textarea, number, date, select, radio, checkbox, repeater (new), file. Choice fields exist **only** where the source itself states the alternatives or clauses.', '')
  lines.push('## Mandatory status policy', '',
    '- `required` — party identity (name + ID/commercial register) and the core terms a lawyer cannot draft without (subject, price/rent/fee, term dates); documents in column H that are unconditional.',
    '- optional — explicit «إن وجد / إن وجدت / اختياري», and **every** column-G field (customer choices). The validator rejects a required field on an explicitly optional item.',
    '- **pending legal review** — the source does not make the status clear (situational items, alternatives, schedules, registry numbers). Never enforced; shown to admins with a "review" badge in the form builder.', '')
  lines.push('## Per contract', '',
    '| Ref | Contract | Steps | Inputs | Required | Optional | Pending review | Files (req/opt) | Lists | Items covered |', '|---|---|---|---|---|---|---|---|---|---|')
  for (const r of rows) {
    const steps = r.compiled.filter(x => x.req === 'section').length
    lines.push(`| ${r.c.ref} | ${esc(short(r.c.nameAr, 50))} | ${steps} | ${r.report.inputCount} | ${r.report.required} | ${r.report.optional} | ${r.report.review} | ${r.report.requiredFiles}/${r.report.fileFields - r.report.requiredFiles} | ${r.report.repeaters} | ${r.report.itemsCovered}/${r.report.itemsTotal} |`)
  }
  lines.push('', '## Fields whose mandatory status needs legal review', '')
  for (const r of rows) {
    const review = r.compiled.filter(x => x.req === 'review')
    if (!review.length) continue
    lines.push(`- **${r.c.ref} — ${r.c.nameAr}**: ${review.map(x => `${x.field.label.ar}${x.field.type === 'file' ? ' (مرفق)' : ''}`).join('، ')}`)
  }
  lines.push('', '## Open questions for the client / legal reviewer', '',
    'Raised by the authoring and independent review passes (none blocks the import; each is a one-line edit in the Service Editor):', '',
    '- **IND-006 / IND-016 / IND-018 / IND-019 / IND-028 / IND-031 / IND-032** — fields not literally listed in the source were added as *pending review*: party birth date, commercial register / legal representative of academies, national ID of a workshop/organizer, address «الكاملة». Delete them if the "no extra fields" rule is strict.',
    '- **IND-009 F2** — the "rights covered by the waiver" checkbox lets a customer tick a subset; the source reads as a waiver of all three rights. Legal may prefer one fixed acknowledgement.',
    '- **IND-010 F3** — «أجر المسكن والحضانة» is one amount field; it may mean two separate amounts.',
    '- **IND-018** — travel/return dates are required but the description says «سفر أو مشاركة»; a local tournament may have no travel.',
    '- **IND-022** — the dispute-parties list is required (≥ 2 rows); lawyers/witnesses are optional.',
    '- **IND-028 G2** — «التسجيل بالشهر العقاري» for a car looks wrong (Traffic Department?); kept verbatim.',
    '- **CO-018** — «رسوم التسويق» may be an amount or a percentage: it is a plain text field marked *pending review*. **CO-021** «رسوم المرتجعات» is a number in EGP (same ambiguity).',
    '- **CO-001 vs CO-022** — profit-share lists are `review` in one and `required` in the other; legal should pick one convention.',
    '- **CO-003** — «حق الاسترداد» is rendered "right of redemption"; legal should confirm the English term (pre-emption / retrieval).',
    '- **CO-006 / CO-008 vs CO-017…CO-029** — contract term/duration is `review` in some employment contracts and `required` in several commercial ones; open-ended terms are possible.',
    '- **CO-032** — the consultant’s tax card is `review` as a party field but required as a document (H2).',
    '- **Translations** — all English copy (titles, descriptions, labels, options) is generated and flagged `pending_review`; the English service page says so. British/American spelling is mixed (licence/license, metre, organiz-).',
    '- **Either/or documents** — items such as «سند ملكية البائع أو التوكيل» are one upload slot (several files allowed).', '')
  return `${lines.join('\n')}\n`
}

