/**
 * Step 5 — generate the data-derived reports from the extracted source + specs.
 *
 *   npx vite-node scripts/catalog-import/report.ts
 *
 * Writes docs/catalog-import/{source-reconciliation,category-mapping,pricing-validation,form-coverage}.md.
 * (implementation-report.md is written by hand because it records test runs and decisions.)
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { buildImportPayload, type CategoryDef, type ExistingMapping } from '../../shared/catalog/build.ts'
import { pricingFor, validatePricing } from '../../shared/catalog/pricing.ts'
import { allItemRefs, sourceItems, type SourceContract } from '../../shared/catalog/source.ts'
import { validateSpec } from '../../shared/catalog/spec.ts'

const DATA = fileURLToPath(new URL('./data/', import.meta.url))
const DOCS = fileURLToPath(new URL('../../docs/catalog-import/', import.meta.url))
const read = <T>(path: string): T => JSON.parse(readFileSync(`${DATA}${path}`, 'utf8'))

const contracts = read<SourceContract[]>('source/contracts.source.json')
const manifest = read<{ workbooks: { file: string, sha256: string, worksheets: string[], role: string }[] }>('source/source-manifest.json')
const categories = read<CategoryDef[]>('categories.json')
const mapping = read<ExistingMapping & { services: { slug: string, decision: string, contractRef?: string, reason: string, needsConfirmation?: string, overlapsWith?: string[] }[] }>('existing-catalog-mapping.json')
const specs = new Map<string, unknown>(readdirSync(`${DATA}specs/`).filter(f => f.endsWith('.json')).map(f => [f.replace('.json', ''), read<unknown>(`specs/${f}`)]))
const { payload } = buildImportPayload({ contracts, specs, categories, mapping })

const esc = (s: string) => s.replace(/\|/g, '\\|')
const egp = (n: number | null) => (n === null ? '—' : n.toLocaleString('en-US'))
const short = (n: string, max = 60) => (n.length > max ? `${n.slice(0, max - 1)}…` : n)

// ---------------------------------------------------------------------------
// 1. source reconciliation
// ---------------------------------------------------------------------------
function reconciliation(): string {
  const restored = contracts.filter(c => c.provenance.restoredColumns.length)
  const lines: string[] = []
  lines.push('# Source reconciliation — three workbooks, 64 contracts', '')
  lines.push('Generated by `scripts/catalog-import/extract.ts` + `report.ts`. The workbooks themselves are **not** committed; their SHA-256 hashes pin exactly what was read.', '')
  lines.push('## Workbooks', '', '| File | SHA-256 | Worksheets | Role |', '|---|---|---|---|')
  for (const w of manifest.workbooks) lines.push(`| ${esc(w.file)} | \`${w.sha256.slice(0, 16)}…\` | ${w.worksheets.map(s => `"${esc(s)}"`).join(', ')} | ${w.role} |`)
  lines.push('', '## Method and precedence', '',
    '1. Every row of the consolidated workbook (two sheets) was compared cell by cell with the matching row of the detailed workbook (`Sheet1`), columns A–N (individuals) and A–R (companies).',
    '2. **Text columns (B–I)**: the detailed workbook wins; a blank cell in the consolidated workbook is restored from it.',
    '3. **Price columns**: the consolidated workbook is the reference; the detailed workbook must agree. Any disagreement is a *commercial conflict* — extraction **stops** instead of choosing a number (none occurred).',
    '4. No hidden rows, merged cells, formulas, comments or extra worksheets were found. All price cells are numeric.', '')
  lines.push('## Result', '',
    '| | Count |', '|---|---|',
    `| Contracts found | **${contracts.length}** (${contracts.filter(c => c.catalog === 'individuals').length} individuals + ${contracts.filter(c => c.catalog === 'companies').length} companies) |`,
    `| Rows identical in both workbooks | ${contracts.length - restored.length} |`,
    `| Rows with a discrepancy | **${restored.length}** |`,
    '| Text conflicts (both filled, different) | 0 |', '| Price conflicts | 0 |', '')
  lines.push('### Discrepancy', '')
  for (const c of restored) {
    for (const d of c.provenance.discrepancies) {
      lines.push(`- **${c.ref} — «${c.nameAr}»** (contract number ${c.number}): ${d.detail}`)
      lines.push(`  - Resolution: ${d.resolution}`)
    }
  }
  lines.push('', '### Source observations (not discrepancies)', '',
    '- CO-016 attachments (column H, item 2) read «قائمة الأصعار والمواصفات» — an apparent typo for «الأسعار». The form label uses «الأسعار»; the raw source text is preserved in `contracts.source.json`.',
    '- IND-028 special condition G2 refers to registration at «الشهر العقاري» for a car (normally the Traffic Department). Kept verbatim; the client should confirm.',
    '- Column I (turnaround) is stored verbatim («1 - 2 يوم عمل», «2 - 3 أيام عمل», «1 يوم عمل»).', '')
  lines.push('## Row-by-row', '',
    '| # | Ref | Contract (AR) | Detailed workbook · sheet · row | Consolidated workbook · sheet · row | Result |', '|---|---|---|---|---|---|')
  contracts.forEach((c, i) => {
    const d = c.provenance.detailed
    const k = c.provenance.consolidated
    const result = c.provenance.restoredColumns.length
      ? `**Restored** columns ${c.provenance.restoredColumns.join(', ')} from the detailed workbook`
      : 'Identical'
    lines.push(`| ${i + 1} | ${c.ref} | ${esc(c.nameAr)} | ${esc(d.workbook)} · ${esc(d.sheet)} · row ${d.row} | ${esc(k.workbook)} · ${esc(k.sheet)} · row ${k.row} | ${result} |`)
  })
  return `${lines.join('\n')}\n`
}

// ---------------------------------------------------------------------------
// 2. category mapping
// ---------------------------------------------------------------------------
function categoryMapping(): string {
  const lines: string[] = []
  lines.push('# Category architecture and existing-catalog mapping', '')
  lines.push('## Design (smallest compatible change)', '',
    '- `service_categories.parent_id` (nullable, two levels only, guarded by a trigger). The three top-level categories — **Individuals**, **Companies**, **Legal Consultations** — are unchanged and no sub-category was created under consultations.',
    '- A contract’s `primary_category_id` is its **sub-category**; a trigger keeps the parent linked in `service_category_links`, so the existing top-level filter (`categoryIds.includes(top.id)`) and the new sub-category filter are both exact.',
    '- No duplicate category records (unique slug; verified by an integration test). Icons are whitelisted by a CHECK constraint (`service_categories_icon_check`).',
    '- URLs: `/services/:category` and `/services/:category/:sub` (a sub-category under the wrong parent is a 404); contract pages stay `/service/:slug`.', '')
  for (const [catalog, title] of [['individuals', 'Individuals'], ['companies', 'Companies']] as const) {
    const subs = categories.filter(c => c.catalog === catalog)
    lines.push(`## ${title} — ${subs.length} sub-categories, ${subs.reduce((n, c) => n + c.expectedCount, 0)} contracts`, '',
      '| # | Sub-category (AR) | English | Slug | Icon | Contracts |', '|---|---|---|---|---|---|')
    subs.forEach(c => lines.push(`| ${c.sortOrder} | ${esc(c.title.ar)} | ${esc(c.title.en)} | \`${c.slug}\` | ${c.icon} | ${c.expectedCount} |`))
    lines.push('')
    for (const c of subs) {
      lines.push(`### ${c.title.ar} (${c.expectedCount}) — \`/services/${c.parentSlug}/${c.slug}\``, '', '| Ref | Contract | Slug |', '|---|---|---|')
      for (const s of payload.services.filter(x => x.categorySlug === c.slug)) lines.push(`| ${s.ref} | ${esc(s.title.ar)} | \`${s.slug}\` |`)
      lines.push('')
    }
  }
  lines.push('## Existing services → decision', '',
    mapping.note ? `${(mapping as unknown as { note: string }).note}` : '', '',
    '| Existing service | Decision | Contract | Reason / open question |', '|---|---|---|---|')
  for (const s of mapping.services) {
    const decision = s.decision === 'reuse' ? '**Reuse / update**' : 'Retain unchanged'
    lines.push(`| \`${s.slug}\` | ${decision} | ${s.contractRef ?? '—'} | ${esc(s.reason)}${s.needsConfirmation ? ` **Needs confirmation:** ${esc(s.needsConfirmation)}` : ''} |`)
  }
  const reused = mapping.services.filter(s => s.decision === 'reuse').length
  lines.push('', '### Totals', '',
    `- Contracts in the catalog: **64** — **${64 - reused} new** services created, **${reused} existing** services matched and updated in place (same id/slug; old form versions retired, never edited or deleted).`,
    `- Existing services retained unchanged: **${mapping.services.filter(s => s.decision === 'retain').length}** (3 generic: \`contract-drafting\`, \`contract-review\`, \`company-formation\` plus \`legal-notice\`, and the 2 consultation services).`,
    '- Archived or deleted automatically: **0**. Potential duplicates needing a decision: see "Needs confirmation" above (lease scope, employment scope, governance price, formation overlap).', '')
  return `${lines.join('\n')}\n`
}

