/**
 * Step 4 — verify the database against the client's workbooks, contract by contract.
 *
 *   npx vite-node scripts/catalog-import/verify.ts                     # local DB (default)
 *   npx vite-node scripts/catalog-import/verify.ts -- --db <postgres-url> --http http://localhost:3000
 *
 * Prints a matrix (13 DB checks + the detail route) and exits 1 unless EVERY one of the 64 rows passes.
 * Read-only: it only SELECTs. `--write` also writes docs/catalog-import/verification-matrix.md.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import pg from 'pg'
import { CHECKS, verifyCatalog } from '../../shared/catalog/verify.ts'
import type { CategoryDef } from '../../shared/catalog/build.ts'
import type { SourceContract } from '../../shared/catalog/source.ts'
import { fetchDbServices } from './db.ts'

const DATA = fileURLToPath(new URL('./data/', import.meta.url))
const DOC = fileURLToPath(new URL('../../docs/catalog-import/verification-matrix.md', import.meta.url))
const args = process.argv.slice(2).filter(a => a !== '--')
const opt = (name: string) => (args.includes(`--${name}`) ? args[args.indexOf(`--${name}`) + 1] : undefined)
const dbUrl = opt('db') ?? 'postgresql://postgres:postgres@127.0.0.1:55322/postgres'
const httpBase = opt('http')

const contracts: SourceContract[] = JSON.parse(readFileSync(`${DATA}source/contracts.source.json`, 'utf8'))
const categories: CategoryDef[] = JSON.parse(readFileSync(`${DATA}categories.json`, 'utf8'))
const specs = new Map<string, unknown>(
  readdirSync(`${DATA}specs/`).filter(f => f.endsWith('.json')).map(f => [f.replace('.json', ''), JSON.parse(readFileSync(`${DATA}specs/${f}`, 'utf8'))]),
)

const client = new pg.Client({ connectionString: dbUrl })
await client.connect()
const services = await fetchDbServices(async text => (await client.query(text)).rows)
await client.end()

const rows = verifyCatalog({ contracts, specs, categories, services })

// detail route (optional)
const routeResults = new Map<string, string>()
if (httpBase) {
  for (const r of rows) {
    if (!r.slug) continue
    const res = await fetch(`${httpBase}/service/${r.slug}`)
    routeResults.set(r.ref, res.status === 200 ? 'ok' : `HTTP ${res.status}`)
  }
}

const lines: string[] = []
const header = ['Ref', 'Slug', ...CHECKS, ...(httpBase ? ['route'] : []), 'Result']
lines.push(`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`)
let failed = 0
for (const r of rows) {
  const route = routeResults.get(r.ref)
  const ok = r.ok && (!httpBase || route === 'ok')
  if (!ok) failed++
  lines.push(`| ${[r.ref, r.slug ?? '—', ...CHECKS.map(k => (r.results[k]?.ok ? '✓' : `✗ ${r.results[k]?.detail ?? ''}`)), ...(httpBase ? [route === 'ok' ? '✓' : `✗ ${route}`] : []), ok ? '**PASS**' : '**FAIL**'].join(' | ')} |`)
}
console.log(lines.join('\n'))
console.log(`\n${rows.length - failed}/${rows.length} contracts verified${httpBase ? ' (incl. detail routes)' : ''}`)

if (args.includes('--write')) {
  const doc = `# Verification matrix (source workbooks → database${httpBase ? ' → detail route' : ''})\n\n`
    + `Generated by \`scripts/catalog-import/verify.ts\`. ✓ = verified programmatically against the extracted workbook rows.\n\n${lines.join('\n')}\n\n**${rows.length - failed}/${rows.length}** contracts verified.\n`
  writeFileSync(DOC, doc, 'utf8')
  console.log(`wrote ${DOC}`)
}
process.exit(failed ? 1 : 0)
